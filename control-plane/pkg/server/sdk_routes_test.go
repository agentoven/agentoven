package server

import (
	"context"
	"encoding/json"
	"net/http"
	"os"
	"regexp"
	"strings"
	"testing"

	"github.com/go-chi/chi/v5"
)

var placeholder = regexp.MustCompile(`\{[^}]*\}`)

// normalizeRoute makes a chi pattern comparable: parameter names do not matter, a trailing slash does not.
func normalizeRoute(p string) string {
	p = placeholder.ReplaceAllString(p, "{}")
	if len(p) > 1 {
		p = strings.TrimRight(p, "/")
	}
	return p
}

// TestSDKRouteFixtureHasEveryCommunityRoute keeps sdk/fixtures/server-routes.json, which the SDK contract
// tests check every client call against, from missing a route the community server serves. The file is
// generated by the Pro repository's route test (it lists Pro's routes as well); a community route added
// without regenerating it fails here, in this repository's build.
func TestSDKRouteFixtureHasEveryCommunityRoute(t *testing.T) {
	raw, err := os.ReadFile("../../../sdk/fixtures/server-routes.json")
	if err != nil {
		t.Fatalf("sdk/fixtures/server-routes.json: %v (regenerate it: UPDATE_SDK_ROUTES=1 go test ./internal/routeguard -run SDKRoute, in agentoven-pro)", err)
	}
	var fixture struct {
		Routes []struct{ Method, Path string } `json:"routes"`
	}
	if err := json.Unmarshal(raw, &fixture); err != nil {
		t.Fatal(err)
	}
	have := map[string]bool{}
	for _, r := range fixture.Routes {
		have[r.Method+" "+normalizeRoute(r.Path)] = true
	}

	srv, err := New(context.Background())
	if err != nil {
		t.Fatal(err)
	}
	var missing []string
	_ = chi.Walk(srv.Mux, func(method, route string, _ http.Handler, _ ...func(http.Handler) http.Handler) error {
		if k := method + " " + normalizeRoute(route); !have[k] {
			missing = append(missing, k)
		}
		return nil
	})
	if len(missing) > 0 {
		t.Fatalf("%d community routes are not in sdk/fixtures/server-routes.json (UPDATE_SDK_ROUTES=1 go test ./internal/routeguard -run SDKRoute, in agentoven-pro):\n  %s",
			len(missing), strings.Join(missing, "\n  "))
	}
}
