// Command docgen writes the parts of the public documentation that must not
// drift from the code: the HTTP endpoint inventory (as an OpenAPI document and
// a reference page) and the provider capability matrix.
//
//	go run ./cmd/docgen -content ../../agentoven-main/agentoven-docs/content \
//	                    -public  ../../agentoven-main/agentoven-docs/public
//
// It builds the real router on an in-memory store and walks it, so a route
// exists in the docs exactly when it exists in the server. Request and response
// schemas are not derived yet; the OpenAPI document says so.
package main

